export default async function Home() {
  let categories = [];
  let breakingNews = [];
  let articles = [];
  let videos = [];
  let socialLinks = null;

  try {
    const [catRes, breakRes, artRes, fetchedVideos, fetchedSocial] = await Promise.all([
      supabase.from("categories").select("*").order("display_order"),
      supabase.from("breaking_news").select("*").eq("is_active", true).order("priority"),
      supabase.from("articles").select("*, categories(*)").order("created_at", { ascending: false }).limit(60),
      getVideos().catch(() => []),
      getSiteSetting("social_links").catch(() => null),
    ]);

    if (catRes.data && catRes.data.length > 0) categories = catRes.data;
    if (breakRes.data && breakRes.data.length > 0) breakingNews = breakRes.data;
    if (artRes.data && artRes.data.length > 0) {
      articles = filterPublishedArticles(artRes.data);
    }
    videos = fetchedVideos || [];
    socialLinks = fetchedSocial || null;
  } catch (err) {
    console.error("Supabase fetch error, using fallback data:", err);
  }

  // Use ONLY real database articles whenever Supabase has articles (never pad with fake fallback posts)
  const sourceList = articles.length > 0 ? articles : fallbackArticles;

  const newsList = sourceList.map((art) => ({
    ...art,
    cover_image:
      art.cover_image && typeof art.cover_image === "string" && art.cover_image.trim()
        ? art.cover_image
        : "/logo-light.webp",
    title_ur: art.title_ur || "",
    title_en: art.title_en || "",
    summary_ur: art.summary_ur || "",
    summary_en: art.summary_en || "",
    author_name: art.author_name || "ایڈیٹوریل بورڈ",
    author_name_en: art.author_name_en || art.author_name || "Editorial Board",
    category: art.categories || art.category || { name_ur: "پاکستان", name_en: "Pakistan", slug: "pakistan" },
    views_count: Number(art.views_count) || 0,
  }));

  // Extract breaking news directly from articles with is_breaking = true
  const articleBreaking = articles
    .filter((a) => a.is_breaking && a.title_ur && a.title_ur.trim())
    .map((a) => ({
      id: `art-${a.id}`,
      text_ur: a.title_ur,
      text_en: a.title_en || a.title_ur,
      link_url: `/story/${a.id || a.slug}`,
      article_id: a.id,
      priority: 0,
      is_active: true,
    }));

  // Combine with breaking_news table, putting live article breaking headlines first
  const allBreaking = [...articleBreaking];
  for (const b of breakingNews) {
    if (!b.text_ur || !b.text_ur.trim()) continue;
    const exists = allBreaking.some(
      (item) => item.text_ur?.trim() === b.text_ur?.trim() || (b.link_url && item.link_url === b.link_url)
    );
    if (!exists) {
      allBreaking.push({
        ...b,
        text_en: b.text_en || b.text_ur,
      });
    }
  }

  return (
    <HomeClient
      articles={newsList}
      categories={categories}
      breakingNews={allBreaking}
      videos={videos}
      socialLinks={socialLinks}
    />
  );
}
